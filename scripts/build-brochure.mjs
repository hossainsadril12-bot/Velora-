#!/usr/bin/env node
/**
 * Converts the Velora brochure PDF into web-ready flip-book assets.
 *
 *   node scripts/build-brochure.mjs [path/to/brochure.pdf]
 *
 * PDF layout: page 1 = front cover (square), pages 2..N-1 = two-page spreads
 * (2:1), page N = back cover (square). Spreads are split into left/right book
 * pages, so a 13-page PDF becomes 24 book pages.
 *
 * Requires poppler's `pdftoppm` on PATH (or POPPLER_BIN pointing at its bin
 * folder) and `sharp` (installed with Next.js).
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const PDF = path.resolve(process.argv[2] ?? path.join(ROOT, "Asset", "Eiman Estates - Velora_Brochure (Digital) v5.3.pdf"));
const OUT = path.join(ROOT, "public", "brochure");
const MANIFEST = path.join(ROOT, "src", "lib", "brochure.ts");

const PAGE_PX = 1600;
const THUMB_PX = 240;
const RENDER_DPI = 240; // 504pt (7in) page -> 1680px, just above PAGE_PX

const pdftoppm = process.env.POPPLER_BIN ? path.join(process.env.POPPLER_BIN, "pdftoppm") : "pdftoppm";

if (!fs.existsSync(PDF)) {
  console.error(`PDF not found: ${PDF}`);
  process.exit(1);
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "brochure-"));
console.log(`Rendering ${path.basename(PDF)} at ${RENDER_DPI} dpi...`);
execFileSync(pdftoppm, ["-r", String(RENDER_DPI), "-png", PDF, path.join(tmp, "p")], { stdio: "inherit" });

const rendered = fs
  .readdirSync(tmp)
  .filter((f) => f.endsWith(".png"))
  .sort()
  .map((f) => path.join(tmp, f));

if (rendered.length < 3) {
  console.error(`Expected at least 3 PDF pages, got ${rendered.length}`);
  process.exit(1);
}

// Collect book pages as sharp inputs (full image or a half of a spread).
const bookPages = [];
for (const [i, file] of rendered.entries()) {
  const { width, height } = await sharp(file).metadata();
  const isSpread = width > height * 1.5;
  const isCover = i === 0 || i === rendered.length - 1;
  if (isSpread && !isCover) {
    const half = Math.floor(width / 2);
    bookPages.push({ file, region: { left: 0, top: 0, width: half, height } });
    bookPages.push({ file, region: { left: half, top: 0, width: width - half, height } });
  } else {
    bookPages.push({ file, region: null });
  }
}

for (const dir of ["pages", "thumbs"]) {
  fs.rmSync(path.join(OUT, dir), { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, dir), { recursive: true });
}

for (const [i, { file, region }] of bookPages.entries()) {
  const id = String(i + 1).padStart(2, "0");
  const base = () => (region ? sharp(file).extract(region) : sharp(file));
  await base()
    .resize(PAGE_PX, PAGE_PX, { fit: "cover" })
    .webp({ quality: 82 })
    .toFile(path.join(OUT, "pages", `page-${id}.webp`));
  await base()
    .resize(THUMB_PX, THUMB_PX, { fit: "cover" })
    .webp({ quality: 70 })
    .toFile(path.join(OUT, "thumbs", `page-${id}.webp`));
  process.stdout.write(`  page ${id}\r`);
}

fs.copyFileSync(PDF, path.join(OUT, "velora-brochure.pdf"));
fs.rmSync(tmp, { recursive: true, force: true });

const total = bookPages.length;
const manifest = `// Generated by scripts/build-brochure.mjs — do not edit by hand.

export type BrochurePage = {
  /** 1-based book page number */
  n: number;
  src: string;
  thumb: string;
  alt: string;
};

export const BROCHURE_PDF = "/brochure/velora-brochure.pdf";

export const BROCHURE_PAGES: BrochurePage[] = Array.from({ length: ${total} }, (_, i) => {
  const n = i + 1;
  const id = String(n).padStart(2, "0");
  return {
    n,
    src: \`/brochure/pages/page-\${id}.webp\`,
    thumb: \`/brochure/thumbs/page-\${id}.webp\`,
    alt:
      n === 1
        ? "Velora brochure — front cover"
        : n === ${total}
          ? "Velora brochure — back cover"
          : \`Velora brochure — page \${n}\`,
  };
});
`;
fs.writeFileSync(MANIFEST, manifest);

console.log(`\nDone: ${total} pages -> public/brochure, manifest -> src/lib/brochure.ts`);
